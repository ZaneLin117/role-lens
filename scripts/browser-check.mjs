  await page.waitForFunction(n=>document.querySelector('[data-testid="result-count"]')?.textContent===String(n),females);
  await page.getByRole('button',{name:'限女性',exact:true}).click();
  await page.getByLabel('筛选学历',{exact:true}).click();
  const educationOptions=page.locator('.multi[open] .option-list input[type=checkbox]');
  await educationOptions.nth(0).check();await educationOptions.nth(1).check();
