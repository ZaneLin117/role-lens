  assert.ok(expected.length>0);
  await page.locator('.detail-button').first().click();await page.getByText('备注原文',{exact:true}).waitFor();
  assert.ok((await page.locator('.original-note').innerText()).includes('男性'));
  await page.keyboard.press('Escape');await page.locator('.detail-dialog').waitFor({state:'detached'});
  await page.locator('.favorite-button').first().click();
  await page.getByRole('button',{name:/我的收藏/}).click();await page.getByTestId('result-count').filter({hasText:'1'}).waitFor();
  await page.getByRole('button',{name:'全部岗位',exact:true}).click();
  await page.getByRole('button',{name:'保存筛选',exact:true}).click();
  const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'导出结果',exact:true}).click()]);
  const exportPath=path.join(root,'.local','export-check.xlsx');await download.saveAs(exportPath);
  const exported=XLSX.read(fs.readFileSync(exportPath));const records=XLSX.utils.sheet_to_json(exported.Sheets.筛选结果);
  assert.equal(records.length,expected.length);assert.ok(records.every(r=>r.来源工作表==='福建'));
  await page.screenshot({path:path.join(root,'.local',offline?'offline-desktop.png':'desktop.png'),fullPage:true});
  // Check all-column filters and show no-result state without a runtime error.
  await page.getByRole('button',{name:'清除全部',exact:true}).click();
  await page.getByLabel('选择列',{exact:true}).selectOption('职位代码');
  await page.getByLabel('包含文字',{exact:true}).fill('DOES-NOT-EXIST');
  await page.getByText('没有找到符合条件的岗位',{exact:true}).waitFor();
  await page.getByRole('button',{name:'查看全部岗位',exact:true}).click();
  // Common-column multiselect uses OR and clearing restores the full sheet.
  await page.getByRole('button',{name:'限女性',exact:true}).click();
