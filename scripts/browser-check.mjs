  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(root,'.local',offline?'offline-mobile.png':'mobile.png'),fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({mode:offline?'offline-file':'dev',importRows:book.sheets.map(s=>[s.name,s.rows.length]),filtered:expected.length,exportRows:records.length,exportBeyondPage:686,multiselect:true,femaleShortcut:true,runtimeErrors:errors.length,mobileOverflow:false}));
